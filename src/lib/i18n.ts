const DICTS = { es, en };

export function t(key: Key, params: Record<string, string | number> = {}): string {
	let s = DICTS[settings.lang][key] ?? es[key] ?? key;
	for (const [k, v] of Object.entries(params)) s = s.replace(`{${k}}`, String(v));
	return s;
}

/** Para claves armadas en tiempo de ejecución (niveles, categorías, voces). */
export function tDynamic(key: string, fallback = key): string {
	return (DICTS[settings.lang] as Record<string, string>)[key] ?? fallback;
}
